#!/usr/bin/env node
// Seed -> brand: one seed colour in, a full brand block out (scale + tinted neutrals + shadows + radius preset).
// Method: take hue + saturation from the seed, then rebuild every step of the reference (default) scale at the
// SAME RELATIVE LUMINANCE. Contrast ratios are therefore inherited from the verified reference by construction,
// and the script re-measures every pair in scripts/contrast-pairs.mjs to prove it.
//   node scripts/seed-to-scale.mjs --seed "#8a3b7d" --name demo --radius round --out src/brand-demo.css
import fs from 'node:fs';
import { collect, resolve, read } from './lib/css-tokens.mjs';
import { hexToHsl, hexForLuminance, luminance, contrast, hexToRgb } from './lib/color.mjs';
import { PAIRS, REQUIRED } from './contrast-pairs.mjs';

const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? process.argv[i + 1] : d; };
const seed = arg('seed'); const name = arg('name'); const radius = arg('radius', 'same'); const out = arg('out', `src/brand-${name}.css`);
if (!seed || !name) { console.error('usage: seed-to-scale.mjs --seed "#rrggbb" --name <brand> [--radius same|round] [--out file]'); process.exit(2); }

const tokensCss = read('src/tokens.css');
const ref = collect([tokensCss], 'default');
const refHex = (t) => resolve(ref, ref['--' + t]).toLowerCase();
const { h: hue, s: seedSat } = hexToHsl(seed);
const refSat600 = hexToHsl(refHex('brand-600')).s;
const k = Math.min(1.6, Math.max(0.6, seedSat / refSat600));

const retint = (token) => { const r = refHex(token); const { s } = hexToHsl(r); return hexForLuminance(hue, Math.min(1, s * k), luminance(r)); };
const neutral = (token) => { const r = refHex(token); const { s } = hexToHsl(r); return hexForLuminance(hue, s, luminance(r)); }; // neutrals keep reference saturation
const steps = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const scale = Object.fromEntries(steps.map(n => [n, retint('brand-' + n)]));
const neutrals = ['background', 'surface-subtle', 'surface-muted', 'surface-hero', 'surface-cta', 'foreground', 'muted-foreground', 'subtle-foreground',
  'foreground-inverse', 'inverse-link', 'inverse-muted', 'border', 'border-strong', 'border-outline', 'border-control'];
const nv = Object.fromEntries(neutrals.map(t => [t, neutral(t)]));
const rgb = (hex) => hexToRgb(hex).join(' ');
const radii = radius === 'round'
  ? { badge: '8px', field: '12px', button: '14px', search: '16px', tile: '16px', card: '18px', panel: '20px', hero: '28px' } : null;

let css = `/* Generated by scripts/seed-to-scale.mjs --seed ${seed} --name ${name} --radius ${radius}. Edit the seed, not this file. */\n[data-brand="${name}"] {\n  /* Brand scale (luminance-matched to the default scale) */\n`;
css += '  ' + steps.map(n => `--brand-${n}:${scale[n]};`).join(' ') + '\n';
css += '  /* Tinted neutrals (same relative luminance as the default neutrals) */\n';
css += '  ' + ['background', 'surface-subtle', 'surface-muted', 'surface-hero', 'surface-cta'].map(t => `--${t}:${nv[t]};`).join(' ') + '\n';
css += '  ' + ['foreground', 'muted-foreground', 'subtle-foreground', 'foreground-inverse', 'inverse-link', 'inverse-muted'].map(t => `--${t}:${nv[t]};`).join(' ') + '\n';
css += '  ' + ['border', 'border-strong', 'border-outline', 'border-control'].map(t => `--${t}:${nv[t]};`).join(' ') + '\n';
css += `  /* Elevation tinted with the brand */\n  --elevation-card-hover:0 8px 24px rgb(${rgb(scale[800])} / .07);\n  --elevation-popover:0 8px 24px rgb(${rgb(scale[900])} / .12);\n  --elevation-sticky:0 -2px 12px rgb(${rgb(scale[900])} / .08);\n  --elevation-sheet:0 -8px 32px rgb(${rgb(scale[900])} / .18);\n`;
if (radii) css += '  /* Radius preset: round */\n  ' + Object.entries(radii).map(([n, v]) => `--r-${n}:${v};`).join(' ') + '\n';
css += '}\n';
fs.writeFileSync(out, css);

// Verify: re-measure every pair for the new brand.
const vars = collect([tokensCss, css], name);
const hex = (t) => resolve(vars, vars['--' + t]).toLowerCase();
let bad = 0;
for (const [fg, bg, kind] of PAIRS) { const r = contrast(hex(fg), hex(bg)); if (r < REQUIRED[kind]) { bad++; console.log(`FAIL ${fg} on ${bg}: ${r.toFixed(2)} < ${REQUIRED[kind]}`); } }
const nearest = steps.reduce((a, n) => Math.abs(luminance(scale[n]) - luminance(seed)) < Math.abs(luminance(scale[a]) - luminance(seed)) ? n : a, 600);
console.log(`wrote ${out}: seed ${seed} (hue ${hue.toFixed(0)}, sat x${k.toFixed(2)}), nearest step ${nearest} (${scale[nearest]})`);
console.log(`${PAIRS.length - bad}/${PAIRS.length} pairs pass for "${name}"`);
process.exit(bad ? 1 : 0);
