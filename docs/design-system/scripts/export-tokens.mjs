// Exports W3C DTCG tokens: tokens/tokens.json (default brand + shared) and tokens/brands/<name>.json (overrides only).
import fs from 'node:fs';
import { blocks, decls, collect, media, read } from './lib/css-tokens.mjs';

const tokensCss = read('src/tokens.css');
const brandFiles = fs.readdirSync('src').filter(f => /^brand-.*\.css$/.test(f));
const SIZE = ['container-max', 'gutter', 'header-h', 'tabbar-h', 'announce-h', 'nav-h', 'sidebar-w', 'chat-list-w', 'touch-min', 'touch-primary'];

function pathFor(n) {
  if (/^brand-\d+$/.test(n)) return ['color', 'brand', n.split('-')[1]];
  if (/^r-/.test(n)) return ['radius', n.slice(2)];
  if (/^elevation-/.test(n)) return ['shadow', n.slice(10)];
  if (/^fs-/.test(n)) return ['fontSize', n.slice(3)];
  if (/^dur/.test(n)) return ['duration', n === 'dur' ? 'base' : n.slice(4)];
  if (n === 'ease-out') return ['easing', 'out'];
  if (/^z-/.test(n)) return ['zIndex', n.slice(2)];
  if (SIZE.includes(n)) return ['size', n];
  return ['color', n];
}
const typeOf = (p) => ({ color: 'color', radius: 'dimension', shadow: 'shadow', fontSize: 'dimension', duration: 'duration', easing: 'cubicBezier', zIndex: 'number', size: 'dimension' })[p[0]];
function value(p, v) {
  const alias = v.match(/^var\(--([\w-]+)\)$/); if (alias) return `{${pathFor(alias[1]).join('.')}}`;
  if (p[0] === 'shadow') {
    const m = v.match(/^(-?\d+)(?:px)? (-?\d+)px (\d+)px rgb\((\d+) (\d+) (\d+) \/ ([\d.]+)\)$/); if (!m) return v;
    const hx = [m[4], m[5], m[6]].map(x => (+x).toString(16).padStart(2, '0')).join('') + Math.round(parseFloat(m[7]) * 255).toString(16).padStart(2, '0');
    return { color: '#' + hx, offsetX: m[1] + 'px', offsetY: m[2] + 'px', blur: m[3] + 'px', spread: '0px' };
  }
  if (p[0] === 'easing') return v.match(/[\d.]+/g).map(Number);
  if (p[0] === 'zIndex') return Number(v);
  return v;
}
function build(vars, resp = {}) {
  const root = {};
  for (const [k, v] of Object.entries(vars)) {
    const n = k.slice(2), p = pathFor(n); let o = root;
    p.slice(0, -1).forEach(s => o = (o[s] ??= {}));
    const tok = { $type: typeOf(p), $value: value(p, v) };
    const r = {}; for (const [bp, ov] of Object.entries(resp)) if (k in ov) r[bp] = ov[k];
    if (Object.keys(r).length) tok.$extensions = { 'com.marketplace.responsive': r };
    o[p.at(-1)] = tok;
  }
  return root;
}
const base = collect([tokensCss], 'default');
const bp = media(tokensCss);
const resp = { md: bp['48rem'], lg: bp['64rem'], 'lg-fine-pointer': bp['64rem+fine'] };
fs.mkdirSync('tokens/brands', { recursive: true });
fs.writeFileSync('tokens/tokens.json', JSON.stringify({ $description: 'Generated by scripts/export-tokens.mjs from src/tokens.css (default brand).', ...build(base, resp) }, null, 2));
for (const f of brandFiles) {
  const name = f.match(/brand-(.*)\.css/)[1]; const vars = {};
  for (const b of blocks(read('src/' + f))) Object.assign(vars, decls(b.body));
  fs.writeFileSync(`tokens/brands/${name}.json`, JSON.stringify({ $description: `Overrides for [data-brand="${name}"]`, ...build(vars) }, null, 2));
}
fs.copyFileSync('src/tokens.css', 'tokens/tokens.css');
for (const f of brandFiles) fs.copyFileSync('src/' + f, 'tokens/' + f);
console.log(`tokens: ${Object.keys(base).length} variables -> tokens/tokens.json, ${brandFiles.length} brand file(s)`);
