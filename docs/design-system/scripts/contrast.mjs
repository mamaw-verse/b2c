import fs from 'node:fs';
import { collect, resolve, read } from './lib/css-tokens.mjs';
import { contrast } from './lib/color.mjs';
import { PAIRS, REQUIRED, SEED_CLAIMS } from './contrast-pairs.mjs';

const files = ['src/tokens.css', ...fs.readdirSync('src').filter(f => /^brand-.*\.css$/.test(f)).sort().map(f => 'src/' + f)];
const texts = files.map(read);
const brands = ['default', ...files.slice(1).map(f => f.match(/brand-(.*)\.css/)[1])];

export function measure(brand) {
  const vars = collect(texts, brand);
  const hex = (t) => resolve(vars, vars['--' + t] ?? (() => { throw new Error('missing --' + t); })()).toLowerCase();
  return { vars, hex, rows: PAIRS.map(([fg, bg, kind]) => { const r = contrast(hex(fg), hex(bg)); return { fg, bg, kind, fgHex: hex(fg), bgHex: hex(bg), ratio: r, req: REQUIRED[kind], pass: r >= REQUIRED[kind] }; }) };
}

if (process.argv[1].endsWith('contrast.mjs')) {
  let fails = 0; let md = '# Contrast report\n\nGenerated by `npm run contrast` (scripts/contrast.mjs). Do not edit by hand.\nText pairs need 4.5:1; UI boundaries and focus rings need 3:1. Pairs are listed in `scripts/contrast-pairs.mjs`.\n';
  for (const b of brands) {
    const m = measure(b); const bad = m.rows.filter(r => !r.pass); fails += bad.length;
    md += `\n## Brand: ${b}  (${m.rows.length - bad.length}/${m.rows.length} pass)\n\n| Foreground | Background | Fg | Bg | Ratio | Needs | Result |\n|---|---|---|---|---|---|---|\n`;
    for (const r of m.rows) md += `| ${r.fg} | ${r.bg} | ${r.fgHex} | ${r.bgHex} | ${r.ratio.toFixed(2)} | ${r.req} | ${r.pass ? 'pass' : '**FAIL**'} |\n`;
  }
  const d = measure('default');
  md += '\n## Seed claims vs measured (default brand)\n\n| Pair | Claimed | Measured | Match |\n|---|---|---|---|\n';
  for (const [fg, bg, claimed] of SEED_CLAIMS) { const r = contrast(d.hex(fg), d.hex(bg)); md += `| ${fg} on ${bg} | ${claimed} | ${r.toFixed(2)} | ${Math.abs(r - claimed) <= 0.02 ? 'yes' : '**NO**'} |\n`; }
  fs.mkdirSync('docs', { recursive: true }); fs.writeFileSync('docs/contrast.md', md);
  for (const b of brands) for (const r of measure(b).rows.filter(r => !r.pass)) console.log(`FAIL [${b}] ${r.fg} on ${r.bg}: ${r.ratio.toFixed(2)} < ${r.req}`);
  console.log(`contrast: ${brands.length} brand(s), ${fails} failing pair(s) -> docs/contrast.md`);
  process.exit(fails ? 1 : 0);
}
